import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from multiagent.paths import MODELS_ROOT

OUT = ROOT / "multiagent/gpu_queue_commands/gpu_queue_commands_spec_full.json"
PY = "../env3.10/bin/python -u evaluation/renderer.py"
RECEIVER_PY = "../env3.10/bin/python -u evaluation/vanilla.py"
GROUPS = {
    "g1": ["mmlu", "mmmlu-ar", "mmmlu-bn", "mmmlu-de", "mmmlu-es"],
    "g2": ["mmmlu-fr", "mmmlu-hi", "mmmlu-id", "mmmlu-it", "mmmlu-ja"],
    "g3": ["mmmlu-ko", "mmmlu-pt", "mmmlu-sw", "mmmlu-yo", "mmmlu-zh"],
    "cmmlu": ["cmmlu"],
}
COMMON = "--seed 42 --max-new-tokens 64 --save-every 1000 --print-every 2000"
BATCH = {"gemma-3-12b-it": 16, "gemma-2-9b-it": 24, "llama3.2-11b-vision-instruct": 24, "granite-3.3-8b-instruct": 32}
DEFAULT_BATCH = 48
RENDERER_BATCH = {"15H_gemma3_12b_to_qwen3_4b": 8, "15B_qwen3_4b_to_gemma2_9b": 12, "15D_ministral3_8b_to_llama32_11b": 12}
DEFAULT_RENDERER_BATCH = 12

VANILLA = {
    "qwen3-4b": ("qwen3-4b", False),
    "llama3-8b-instruct": ("llama3-8b-instruct", False),
    "gemma-2-9b-it": ("gemma-2-9b-it", False),
    "granite-3.3-8b-instruct": ("granite-3.3-8b-instruct", False),
    "smollm3-3b": (str(MODELS_ROOT / "HuggingFaceTB/SmolLM3-3B"), False),
    "ministral-3-8b-instruct": ("ministral-3-8b-instruct", False),
    "llama3.2-11b-vision-instruct": ("llama3.2-11b-vision-instruct", False),
    "gemma-3-4b-it": ("gemma-3-4b-it", False),
    "gemma-3-12b-it": ("gemma-3-12b-it", False),
}
R = "outputs_mine"
RENDERERS = {
    "14E_qwen3_4b_to_llama3_8b": (f"{R}/swat/14E/stage2/exit-checkpoint-24000", 1, False),
    "15B_qwen3_4b_to_gemma2_9b": (f"{R}/swat/15B/stage2/exit-checkpoint-24000", 1, False),
    "exp1_granite33_8b_to_smollm3_3b": (f"{R}/swat/granite_smollm3/stage2/exit-checkpoint-24000", 1, False),
    "15D_ministral3_8b_to_llama32_11b": (f"{R}/swat/15D/stage2/exit-checkpoint-24000", 2, False),
    "15E_gemma3_4b_to_granite33_8b": (f"{R}/swat/15E/stage2/exit-checkpoint-24000", 1, False),
    "15G_gemma3_4b_to_llama3_8b": (f"{R}/swat/15G/stage2/checkpoint-24000", 1, False),
    "15H_gemma3_12b_to_qwen3_4b": (f"{R}/swat/15H/stage2/checkpoint-24000", 1, False),
}


def tasks(group):
    return " ".join(f"{t}:test" for t in GROUPS[group])


def main():
    jobs = ["# Full specialization sweep: MMMLU (14 langs) + MMLU + CMMLU, all questions, sender/receiver/renderer. "
            "Generated by scripts/specialization/make_specialization_full_queue.py; outputs under outputs_mine/specialization/full/."]
    for pair, (ckpt, gpus, has_cmmlu) in sorted(RENDERERS.items(), key=lambda kv: -kv[1][1]):
        for group in GROUPS:
            if group == "cmmlu" and has_cmmlu:
                continue
            out = f"{R}/specialization/full/renderer/{pair}/{group}.json"
            devices = "--device cuda:0 --sender-device cuda:1" if gpus == 2 else "--device cuda:0"
            bs = RENDERER_BATCH.get(pair, DEFAULT_RENDERER_BATCH)
            jobs.append({"cmd": f"{PY} --renderer {ckpt} --renderer-decode-prefix generation --tasks {tasks(group)} "
                                f"{devices} --max-length 2048 --context-cache-max 4 {COMMON} --batch-size {bs} "
                                f"--chunk-size {2 * bs} --output {out}", "gpus": gpus})
    for key, (model, has_cmmlu) in VANILLA.items():
        for group in GROUPS:
            if group == "cmmlu" and has_cmmlu:
                continue
            out = f"{R}/specialization/full/vanilla/{key}/{group}.json"
            bs = BATCH.get(key, DEFAULT_BATCH)
            jobs.append({"cmd": f"{RECEIVER_PY} --model {model} --tasks {tasks(group)} --device cuda:0 {COMMON} --batch-size {bs} "
                                f"--chunk-size {2 * bs} --output {out}", "gpus": 1})
    for job in jobs:
        if isinstance(job, dict):
            (ROOT / "multiagent" / Path(job["cmd"].split("--output ")[1]).parent).mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(jobs, indent=1) + "\n")
    print(f"wrote {OUT} with {sum(isinstance(j, dict) for j in jobs)} jobs")


if __name__ == "__main__":
    main()
